export function readCatalogUrl(url: URL, items: readonly Item[]) {
  const params = url.searchParams;
  const stackId =
    params.get("stack") ||
    (url.pathname.startsWith("/stacks/") ? url.pathname.split("/")[2] : null);
  let stack = CURATED_STACKS.find((entry) => entry.id === stackId) ?? null;
  // Continue supporting stack links generated by earlier versions of the site.
  if (!stack && url.hash.startsWith("#stack=")) {
    let ids: string[] = [];
    try {
      ids = decodeURIComponent(url.hash.slice(7)).split(",");
    } catch {
      /* Ignore malformed legacy links. */
    }
    stack =
      CURATED_STACKS.find((entry) =>
        [entry.itemIds, legacyStackIds[entry.id] || []].some(
          (list) =>
            list.length === ids.length && list.every((id) => ids.includes(id)),
        ),
      ) ?? null;
  }
  const category = params.get("category") ?? "all";
  const toolId =
    params.get("tool") ||
    (!url.hash.startsWith("#stack=") ? url.hash.slice(1) : null);
  return {
    query: (params.get("q") ?? "").slice(0, 200),
    category: stack
      ? "stacks"
      : CATEGORIES.includes(category)
        ? category
        : "all",
    tag: [
      "all",
      "macos",
      "windows",
      "linux",
      "web",
      "cli",
      "open-source",
    ].includes(params.get("tag") ?? "all")
      ? (params.get("tag") ?? "all")
      : "all",
    stack,
    tool: items.find((item) => item.id === toolId) ?? null,
  };
}

export function stackShareUrl(origin: string, stack: CuratedStack) {
  const url = new URL(`/stacks/${stack.id}`, origin);
  return url.toString();
}
